const LANG_STORAGE_KEY = "siteLanguage";

let currentLanguage = localStorage.getItem(LANG_STORAGE_KEY) === "pt" ? "pt" : "en";
const listeners = [];

export const getLang = () => currentLanguage;
export const isPt    = () => currentLanguage === "pt";
/** Textos do idioma atual */
export const t       = () => translations[currentLanguage];

/** Registra uma função que (re)aplica os textos de uma parte da página */
export function onLanguageChange(fn) {
  listeners.push(fn);
}

/** Reaplica todos os textos registrados (usado na carga da página e ao trocar idioma) */
export function refreshTranslations() {
  listeners.forEach(fn => fn(currentLanguage));
}

export function toggleLanguage() {
  currentLanguage = currentLanguage === "en" ? "pt" : "en";
  localStorage.setItem(LANG_STORAGE_KEY, currentLanguage);
  document.documentElement.lang = currentLanguage === "pt" ? "pt-br" : "en";
  refreshTranslations();
}
